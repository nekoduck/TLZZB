_QUIP_BAD = re.compile(r'\d|号|投|出|狼|预言|女巫|猎人|平民|村民|白板|民牌|金水|查杀|银水')


def _clean(s: str) -> bool:
    return bool(s) and not _QUIP_BAD.search(s)


def quip(voice: PersonaVoice, key: str, rng: Rng) -> str | None:
    """一句嘀咕：固定词表，按人设的语气词和口头禅略作调味。未知的 key 返回 None。"""
    base = QUIPS.get(key)
    if not base:
        return None
    text = rng.choice(base)
    st = voice.style
    roll = rng.random()
    if roll < 0.35:
        fillers = [f for f in st.fillers if _clean(f)]
        if fillers:
            f = rng.choice(fillers)
            if not text.startswith(f):
                text = f'{f}，{text}'
    elif roll < 0.5 and key in ('doubt', 'thinking', 'amused'):
        cps = [c for c in st.catchphrases if _clean(c)]
        if cps:
            text = rng.choice(cps)
    return text if _clean(text) else rng.choice(base)
